"""Writes figdata.tex (pgfplots coordinates) for the SWARM-20 and SWARM-21 figures, read from their score.json files.
Optional 4th argument: the SWARM-15 s4-score.json, for the simple SWARM-15 figure.
Optional 5th argument: the SWARM-23 swarm23.json, for the full-reply vs. verdict-line figure."""
import json, sys
s20 = json.load(open(sys.argv[1]))["P3"]
s21 = json.load(open(sys.argv[2]))["P4"]
mons = [("dense18", "Probe before reply"), ("tfidf_reply_word", "TF-IDF reply"), ("dense18_public", "Probe on logged text"),
        ("judge_oriented", "Same-model judge")]
out = ["% generated by fig_s20_s21.py; do not edit"]
out.append("\\def\\swtwentylabels{" + ",".join(n for _, n in mons) + "}")
c = s20["catch_all_monitors_S"]
out.append("\\def\\swtwentyprobe{" + f"({c[mons[0][0]]:.3f},{mons[0][1]})" + "}")
out.append("\\def\\swtwentypublic{" + " ".join(f"({c[k]:.3f},{n})" for k, n in mons[1:]) + "}")
out.append("\\def\\swtwentyfpr{" + " ".join(f"({n},{s20['fpr_heldLB_all_monitors'][k]:.3f})" for k, n in mons) + "}")
bv = s21["bait_vs_real"]
conds = [("colluding", "Colluder warned"), ("unwarned", "Colluder unwarned"), ("honest", "Honest")]
out.append("\\def\\swtwentyonelabels{" + ",".join(n for _, n in conds) + "}")
for kind in ("real", "bait"):
    out.append(f"\\def\\swtwentyone{kind}{{" + " ".join(f"({n},{bv[k][kind]:.3f})" for k, n in conds) + "}")
if len(sys.argv) > 4:
    s15 = json.load(open(sys.argv[4]))
    arms = [("C", "Collusive"), ("L", "Legit waiver"), ("B", "Benign"), ("I", "Non-owner waiver")]
    out.append("\\def\\swfifteenarms{" + ",".join(n for _, n in arms) + "}")
    out.append("\\def\\swfifteenapprove{" + " ".join(f"({n},{s15['P0']['approve_fail'][k]:.3f})" for k, n in arms) + "}")
    m15 = [("dense18", "Probe before reply"), ("tfidf_reply_word", "TF-IDF reply"), ("dense18_public", "Probe on logged text"),
           ("judge_oriented", "Same-model judge"), ("rule_approve_fail", "Approval rule")]
    a = {k: s15["reported"][k]["C_vs_LB"]["mean"] for k, _ in m15}
    out.append("\\def\\swfifteenlabels{" + ",".join(n for _, n in m15) + "}")
    out.append("\\def\\swfifteenprobe{" + f"({a['dense18']:.3f},{m15[0][1]})" + "}")
    out.append("\\def\\swfifteenpublic{" + " ".join(f"({a[k]:.3f},{n})" for k, n in m15[1:]) + "}")
if len(sys.argv) > 5:
    s23 = json.load(open(sys.argv[5]))
    arms = [("A_full", "Full reply"), ("B_verdict_only", "Verdict line only")]
    out.append("\\def\\swtwentythreearms{" + ",".join(n for _, n in arms) + "}")
    out.append("\\def\\swtwentythreeprobe{" + " ".join(f"({n},{s23[k]['dense18']['catch']:.3f})" for k, n in arms) + "}")
    out.append("\\def\\swtwentythreelog{" + " ".join(f"({n},{s23[k][s23[k]['best_tfidf']]['catch']:.3f})" for k, n in arms) + "}")
open(sys.argv[3], "w").write("\n".join(out) + "\n")
